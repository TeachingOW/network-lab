#!/usr/bin/env python3
"""Compile api.spec into a C++ header with a branch-only router.

usage: gen_routes.py api.spec build/routes_gen.h
"""
import re
import sys

METHODS = ["GET", "POST", "PUT", "DELETE", "PATCH", "HEAD"]
MAX_SEGS = 8
DEFAULT_MAXBODY = 1 << 20
LINE_RE = re.compile(r"([A-Z]+)\s+(/\S*)\s*->\s*([A-Za-z_]\w*)((?:\s+\w+=\S+)*)$")
LIT_RE = re.compile(r"[A-Za-z0-9._~-]+$")
PARAM_RE = re.compile(r":([A-Za-z_]\w*)$")


def die(msg):
    print(f"gen_routes: {msg}", file=sys.stderr)
    sys.exit(1)


def parse_size(s, where):
    m = re.fullmatch(r"(\d+)([kKmMgG]?)", s)
    if not m:
        die(f"{where}: bad size '{s}'")
    mult = {"": 1, "k": 1 << 10, "m": 1 << 20, "g": 1 << 30}[m.group(2).lower()]
    return int(m.group(1)) * mult


def parse_spec(path):
    routes, seen = [], set()
    with open(path) as f:
        for ln, raw in enumerate(f, 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            where = f"{path}:{ln}"
            m = LINE_RE.match(line)
            if not m:
                die(f"{where}: cannot parse '{line}'")
            method, p, handler, opts = m.groups()
            if method not in METHODS:
                die(f"{where}: unknown method {method}")
            segs = [] if p == "/" else p.strip("/").split("/")
            if len(segs) > MAX_SEGS:
                die(f"{where}: more than {MAX_SEGS} segments")
            kinds, names = [], []
            for s in segs:
                pm = PARAM_RE.match(s)
                if pm:
                    if pm.group(1) in names:
                        die(f"{where}: duplicate param :{pm.group(1)}")
                    names.append(pm.group(1))
                    kinds.append(("param", pm.group(1)))
                elif LIT_RE.match(s):
                    kinds.append(("lit", s))
                else:
                    die(f"{where}: bad segment '{s}'")
            maxbody = DEFAULT_MAXBODY
            for kv in opts.split():
                k, v = kv.split("=", 1)
                if k == "maxbody":
                    maxbody = parse_size(v, where)
                else:
                    die(f"{where}: unknown option '{k}'")
            shape = (method, tuple("*" if k == "param" else s for k, s in kinds))
            if shape in seen:
                die(f"{where}: duplicate route {method} {p}")
            seen.add(shape)
            routes.append(dict(method=method, path=p, handler=handler,
                               kinds=kinds, nparams=len(names), maxbody=maxbody))
    if not routes:
        die("no routes")
    return routes


def emit(routes, out):
    # literal-before-param ordering, so /items/bulk beats /items/:id
    order = sorted(range(len(routes)),
                   key=lambda i: [k == "param" for k, _ in routes[i]["kinds"]])
    nparams = max(1, max(r["nparams"] for r in routes))
    handlers = sorted({r["handler"] for r in routes})
    L = []
    w = L.append
    w("// GENERATED by tools/gen_routes.py from api.spec. DO NOT EDIT.")
    w("#pragma once")
    w("#include <cstddef>\n#include <cstdint>\n#include <string_view>\n")
    w("struct Req;\nstruct Res;")
    w("using HandlerFn = void (*)(const Req&, Res&);")
    w("enum Method : uint8_t { " + ", ".join(f"M_{m}" for m in METHODS) + ", M_UNKNOWN };")
    w(f"static constexpr int kMaxSegs = {MAX_SEGS};")
    w(f"struct Params {{ std::string_view v[{nparams}]; }};\n")
    for h in handlers:
        w(f"void h_{h}(const Req&, Res&);")
    w(f"\nstatic constexpr size_t kNumRoutes = {len(routes)};")
    w("static constexpr HandlerFn kRouteHandler[kNumRoutes] = {")
    for r in routes:
        w(f"    h_{r['handler']},  // {r['method']} {r['path']}")
    w("};")
    w("static constexpr size_t kRouteMaxBody[kNumRoutes] = {")
    for r in routes:
        w(f"    {r['maxbody']}ull,")
    w("};\n")
    w("// Returns route index, -1 = no such path, -2 = path exists, wrong method.")
    w("static inline int route_match(Method m, std::string_view path, Params& p) {")
    w("    std::string_view s[kMaxSegs]; int n = 0;")
    w("    size_t i = (!path.empty() && path[0] == '/') ? 1 : 0;")
    w("    while (i < path.size()) {")
    w("        size_t j = path.find('/', i);")
    w("        if (j == std::string_view::npos) j = path.size();")
    w("        if (n == kMaxSegs) return -1;")
    w("        s[n++] = path.substr(i, j - i);")
    w("        i = j + 1;")
    w("    }")
    w("    bool path_hit = false;")
    for idx in order:
        r = routes[idx]
        conds = [f"n == {len(r['kinds'])}"]
        binds, pi = [], 0
        for pos, (k, v) in enumerate(r["kinds"]):
            if k == "lit":
                conds.append(f's[{pos}] == "{v}"')
            else:
                conds.append(f"!s[{pos}].empty()")
                binds.append(f"p.v[{pi}] = s[{pos}];")
                pi += 1
        w(f"    if ({' && '.join(conds)}) {{ path_hit = true;")
        w(f"        if (m == M_{r['method']}) {{ {' '.join(binds)} return {idx}; }}")
        w("    }")
    w("    return path_hit ? -2 : -1;")
    w("}")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        die("usage: gen_routes.py api.spec out.h")
    emit(parse_spec(sys.argv[1]), sys.argv[2])
